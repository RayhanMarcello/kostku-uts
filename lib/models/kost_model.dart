class Kost {
  final String id;
  final String nama;
  final String tipe;
  final String alamat;
  final int harga;
  final String deskripsi;
  final List<String> fasilitas;
  final String gambar;
  final String namaPemilik;
  final String noPemilik;

  Kost({
    required this.id,
    required this.nama,
    required this.tipe,
    required this.alamat,
    required this.harga,
    required this.deskripsi,
    required this.fasilitas,
    required this.gambar,
    required this.namaPemilik,
    required this.noPemilik,
  });
}
